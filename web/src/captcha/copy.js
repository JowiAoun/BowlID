export function lifeSpent(ms) {
  const s = Math.max(1, Math.round(ms / 1000));
  if (s < 90) return `${s} second${s === 1 ? '' : 's'} of your life`;
  const m = Math.round(s / 60);
  return `${m} minutes of your life`;
}
